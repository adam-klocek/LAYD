# Run from project root: Rscript tests/test_engine.R
source("R/io.R"); source("R/checks.R")
assert <- function(ok, msg) { if (!isTRUE(ok)) stop(msg, call. = FALSE); cat("PASS:", msg, "\n") }
throws <- function(expr) inherits(tryCatch(force(expr), error = function(e) e), "error")
d <- make_demo(); cb <- demo_codebook(d)
s <- list(run_cfa = FALSE, id = "id", group = "language", age = "age", consent = "consent", attention = "attention", duration = "duration", test = "test_account")
r <- analyze_layd(d, cb, s)
assert(identical(d, make_demo()), "Analysis leaves original data intact")
assert(r$prepared$A2[4] %in% NA_real_, "Out-of-range values are withheld")
assert(is.na(r$prepared$A1[9]), "Fractional integer-scale responses are withheld")
assert(is.na(r$prepared$B1[8]), "Explicit sentinel becomes missing")
assert(r$prepared$B4[1] == 6 - d$B4[1], "Declared key uses min + max - value")
assert(r$summaries$item_rest[r$summaries$item == "A3"] < -.4, "Omitted demo key has negative corrected correlation")
cb_fixed <- cb; cb_fixed$reverse[cb_fixed$item == "A3"] <- TRUE
r_fixed <- analyze_layd(d, cb_fixed, s)
assert(r_fixed$summaries$item_rest[r_fixed$summaries$item == "A3"] > .4, "Corrected key restores positive item-rest association")
assert(r_fixed$reliability$alpha[1] > r$reliability$alpha[1], "Correcting key increases complete-case alpha")
assert(all(c(10, 11) %in% r$row_flags$row[r$row_flags$check == "Duplicate ID"]), "Both members of duplicate ID pair are flagged")
assert(12 %in% r$row_flags$row[r$row_flags$check == "Missing ID"], "Missing ID is flagged")
assert(all(c(15,16,17,18,19) %in% r$row_flags$row), "All planted eligibility failures are flagged")
assert(nrow(r$scores) == nrow(d), "No participant is automatically excluded")
assert(is.na(number_values(factor(c("1", "4", "four")))[3]) && number_values(factor(c("1", "4")))[2] == 4,
  "Factors convert literal numeric labels, never level indices")
assert(longest_run(c(3,3,NA,3,3)) == 2, "Missing values break response strings")
assert(longest_run(c(NA,NA)) == 0, "All-missing row has no response string")
small <- data.frame(X1 = c(-2,-1,0,1,2), X2 = c(2,1,0,-1,-2))
smallcb <- make_codebook(small, -2, 2); smallcb$scale <- "X"
z <- analyze_layd(small, smallcb, list(run_cfa = FALSE))
assert(identical(z$prepared$X1, as.numeric(small$X1)), "Legitimate negative values are preserved")
assert(z$models$X$status == "Not assessed", "Disabled model is explicitly unassessed")
allna <- data.frame(Q1 = rep(NA_real_, 10), Q2 = rep(2, 10), Q3 = rep(NA_real_, 10))
rr <- analyze_layd(allna, make_codebook(allna), list(run_cfa = FALSE))
assert(all(is.na(rr$item_cor)), "All-missing/constant correlations remain NA")
assert(all(is.na(rr$scores[[2]])), "Insufficient item completion produces NA, not NaN or zero")
factor_d <- data.frame(F1 = factor(c("1","2","3","4","5")), F2 = c("1","two","3","4","5"))
ff <- analyze_layd(factor_d, make_codebook(factor_d), list(run_cfa = FALSE))
assert(ff$prepared$F1[5] == 5 && is.na(ff$prepared$F2[2]), "Mixed types are logged without guessing category meanings")
assert(any(ff$cells$issue == "Non-numeric item response"), "Mixed text produces a cell-level audit")
assert(throws(validate_codebook(transform(cb, min = 7), d)), "Invalid endpoint definitions are rejected")
assert(throws(validate_codebook(transform(cb, reverse = "maybe"), d)), "Ambiguous reverse-key values are rejected")
assert(nrow(make_codebook(data.frame(name = c("a","b")))) == 0, "Dataset with no numeric items gets an empty codebook")
assert(throws(analyze_layd(data.frame(name = c("a","b")), make_codebook(data.frame(name = c("a","b"))))), "No-item analysis gives an explicit validation error")
unknown_cb <- cb; unknown_cb$item[1] <- "absent"
assert(throws(validate_codebook(unknown_cb, d)), "Unmatched codebook names are rejected")
unsafe <- cb; unsafe$scale <- "row"
assert(throws(validate_codebook(unsafe, d)), "Reserved row index cannot be overwritten by a scale name")
renamed <- check_frame(setNames(data.frame(a = 1:3,b = 1:3,c = 1:3), c("X", "X", "")))
assert(!anyDuplicated(names(renamed)) && names(renamed)[3] == "unnamed", "Duplicate/blank imported names are repaired and recorded")
assert(throws(check_frame(data.frame(x = I(list(1:2, 3:4))))), "Nested columns are rejected")
exp <- data.frame(scale1 = "A", scale2 = "B", expected = .8, tolerance = .05)
ext <- analyze_layd(d, cb, s, exp)
assert(ext$external$status == "Review", "Relationship contradicting prior expectation is flagged")
assert(throws(analyze_layd(d, cb, s, transform(exp, scale2 = "missing"))), "Unknown scale in external expectations is rejected")
prior <- data.frame(item = "A1", expected_mean = 1, tolerance = .01)
pr <- analyze_layd(d, cb, s, priors = prior)
assert(any(pr$findings$check == "Mean versus prior expectation" & pr$findings$status == "Review"), "Prior item mean comparison flags disagreement")
set.seed(123); before <- .Random.seed
invisible(parallel_components(r$prepared[, paste0("B",1:5)]))
assert(identical(before, .Random.seed), "Parallel analysis restores caller RNG state")
# RData selection is independent from the current/global environment.
tf <- tempfile(fileext = ".RData"); people <- d; other <- data.frame(X1 = 1:3); scalar <- 42
save(people, other, scalar, file = tf)
assert(setequal(import_choices(tf, "test.RData"), c("people", "other")), "RData lists all and only tabular objects")
assert(nrow(read_upload(tf, "test.RData", "other")) == 3, "RData imports the explicitly selected object")
unlink(tf)
tf <- tempfile(fileext = ".csv"); writeLines(c("X1;X2", "1,5;2,5", "2,5;3,5"), tf)
cs <- read_upload(tf, "test.csv", sep = ";", dec = ",")
assert(cs$X1[1] == 1.5, "European semicolon/decimal-comma CSV is read correctly")
unlink(tf)
cat("All engine checks passed.\n")
